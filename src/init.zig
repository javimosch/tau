const testing = std.testing;

test "detectKeys finds provider env keys in table order" {
    var ar = std.heap.ArenaAllocator.init(testing.allocator);
    defer ar.deinit();
    const a = ar.allocator();

    var env = std.process.Environ.Map.init(a);
    try env.put("OPENAI_API_KEY", "sk-oai");
    try env.put("XIAOMI_API_KEY", "xm-key");

    const det = try detectKeys(a, &env);
    try testing.expectEqual(@as(usize, 2), det.keys.len);
    // Provider-table order: xiaomi is listed before openai.
    try testing.expectEqualStrings("xiaomi", det.keys[0].provider);
    try testing.expectEqualStrings("XIAOMI_API_KEY", det.keys[0].env_key);
    try testing.expectEqualStrings("openai", det.keys[1].provider);
    try testing.expect(!det.tau_fallback);
}

test "detectKeys reports TAU_API_KEY as the fallback" {
    var ar = std.heap.ArenaAllocator.init(testing.allocator);
    defer ar.deinit();
    const a = ar.allocator();

    var env = std.process.Environ.Map.init(a);
    try env.put("TAU_API_KEY", "tau-key");
    // Empty values don't count as detected.
    try env.put("DEEPSEEK_API_KEY", "");

    const det = try detectKeys(a, &env);
    try testing.expectEqual(@as(usize, 0), det.keys.len);
    try testing.expect(det.tau_fallback);
}

test "pickProvider: explicit > detected > default" {
    var ar = std.heap.ArenaAllocator.init(testing.allocator);
    defer ar.deinit();
    const a = ar.allocator();

    var env = std.process.Environ.Map.init(a);
    try env.put("OPENAI_API_KEY", "sk-oai");
    const det = try detectKeys(a, &env);

    // Explicit --provider beats detection.
    try testing.expectEqualStrings("deepseek", pickProvider(det, "deepseek").name);
    // Detection picks the first provider with a set env key.
    try testing.expectEqualStrings("openai", pickProvider(det, null).name);

    var empty_env = std.process.Environ.Map.init(a);
    const none = try detectKeys(a, &empty_env);
    // Nothing detected, no flag: the in-code default provider.
    try testing.expectEqualStrings(cfgmod.providers[0].name, pickProvider(none, null).name);
    // An unknown explicit name falls back to detection/default.
    try testing.expectEqualStrings("openai", pickProvider(det, "bogus").name);
}

test "renderConfig emits a commented JSONC config that never leaks key values" {
    var ar = std.heap.ArenaAllocator.init(testing.allocator);
    defer ar.deinit();
    const a = ar.allocator();

    var env = std.process.Environ.Map.init(a);
    try env.put("OPENAI_API_KEY", "sk-secret-value");
    const det = try detectKeys(a, &env);
    const p = pickProvider(det, null);

    const body = try renderConfig(a, det, p);
    // Comments present, detected env var referenced by name, chosen provider set.
    try testing.expect(std.mem.indexOf(u8, body, "//") != null);
    try testing.expect(std.mem.indexOf(u8, body, "OPENAI_API_KEY") != null);
    try testing.expect(std.mem.indexOf(u8, body, "\"provider\": \"openai\"") != null);
    // The secret value itself must never be written.
    try testing.expect(std.mem.indexOf(u8, body, "sk-secret-value") == null);

    // Stripped of comments, the body is valid JSON selecting that provider.
    const stripped = try configfile.stripComments(a, body);
    const parsed = try std.json.parseFromSliceLeaky(
        struct { provider: []const u8 },
        a,
        stripped,
        .{ .ignore_unknown_fields = true },
    );
    try testing.expectEqualStrings("openai", parsed.provider);
}

test "renderConfig with no detected keys notes that none were found" {
    var ar = std.heap.ArenaAllocator.init(testing.allocator);
    defer ar.deinit();
    const a = ar.allocator();

    var env = std.process.Environ.Map.init(a);
    const det = try detectKeys(a, &env);
    const body = try renderConfig(a, det, cfgmod.providers[0]);
    try testing.expect(std.mem.indexOf(u8, body, "none detected") != null);
    try testing.expect(std.mem.indexOf(u8, body, "* set") == null);
}
