#!/usr/bin/env bash
# e2e-upgrade-keep-state.sh — previous-stable upgrade e2e.
#
# Proves `tau upgrade` is a binary-only operation: a user upgrading from a
# previous stable release keeps every byte of their tau config, sessions,
# snippets, and editor ACP client wiring — and the upgraded binary still
# reads the old config and validates it clean.
#
#   1. Seed a previous-stable $HOME: commented JSONC config.json in the
#      v0.4.0 key shape (provider/model/api_key/mode/keys — no $schema), a
#      session file, an nvim snippet, and realistic editor settings carrying
#      the tau ACP entry alongside the user's own keys (Zed, VS Code,
#      JetBrains). Client entries point at the installed binary path — the
#      exact path upgrade replaces in place.
#   2. Hash every state file, then run `tau upgrade --yes` against a fully
#      offline file:// release tree (real binary as the v99.9.9 payload, so
#      the post-upgrade binary is runnable; the tag — not the payload —
#      drives the update decision).
#   3. Assert every state file is byte-identical after the upgrade, then
#      drive the NEW binary against the OLD config: `config get` resolves
#      the previous provider and still redacts keys.* secrets, and
#      `config validate` reports the old-format file ok.
#
# Usage: scripts/e2e-upgrade-keep-state.sh <path-to-tau> [scratch-dir]
#   <path-to-tau>   tau binary to exercise — installed as the "previous"
#                   binary AND packed as the "new" release payload
#   [scratch-dir]   scratch playground (default: mktemp -d)
# Env: TAU_E2E_INSTALL_SH overrides the install.sh used (default: sibling
# of this script).
set -euo pipefail

TAU="${1:?usage: e2e-upgrade-keep-state.sh <path-to-tau> [scratch-dir]}"
PS="${2:-$(mktemp -d)}"
FH="$PS/home"
INSTALL_SH="${TAU_E2E_INSTALL_SH:-$(cd "$(dirname "$0")/.." && pwd)/install.sh}"
mkdir -p "$FH"

KEYVARS="XIAOMI_API_KEY PIZIG_API_KEY OPENAI_API_KEY DEEPSEEK_API_KEY OPENCODE_API_KEY TAU_API_KEY TAU_NO_UPDATE_CHECK TAU_YES TAU_ENDPOINT TAU_INSTALL_DIR TAU_INSTALL_URL TAU_UPDATE_URL TAU_BASE_URL TAU_SKIP_CHECKSUM"
run_env() {
  local args=() k
  for k in $KEYVARS; do args+=(-u "$k"); done
  env "${args[@]}" HOME="$FH" "$@"
}

fail() {
  echo "e2e-upgrade-keep-state: FAIL — $*" >&2
  exit 1
}

hash_file() {
  sha256sum "$1" 2>/dev/null | cut -d' ' -f1 || shasum -a 256 "$1" | cut -d' ' -f1
}

# Host platform → release asset name (same mapping install.sh performs).
asset_os=""
case "$(uname -s)" in
  Linux)  asset_os=linux ;;
  Darwin) asset_os=macos ;;
esac
asset_arch="$(uname -m)"
case "$asset_arch" in
  amd64) asset_arch=x86_64 ;;
  arm64) asset_arch=aarch64 ;;
esac
case "$asset_arch" in
  x86_64|aarch64) ;;
  *) asset_arch="" ;;
esac
[ -n "$asset_os" ] && [ -n "$asset_arch" ] || fail "unsupported host platform for asset staging"
ASSET="tau-$asset_os-$asset_arch.tar.gz"

echo "e2e-upgrade-keep-state: home=$FH bin=$TAU"

# ── 1. Seed previous-stable state ───────────────────────────────────────────
mkdir -p "$PS/bin" "$FH/.config/tau/sessions" "$FH/.config/tau/snippets" \
  "$FH/.config/zed" "$FH/.config/Code/User" "$FH/.jetbrains"

# The "installed previous" binary — upgrade replaces this path in place.
cp "$TAU" "$PS/bin/tau"
chmod +x "$PS/bin/tau"

# v0.4.0-era config: JSONC comments, no $schema (added post-0.4.0), keys{}
# map, no keys the validator would flag.
cat > "$FH/.config/tau/config.json" <<'EOF'
// tau configuration — written by `tau init` on the previous stable release.
{
  "provider": "xiaomi",
  "model": "mimo-v2.5",
  "api_key": "sk-prev-stable",
  "mode": "json",
  // per-provider overrides survive upgrades too
  "keys": { "deepseek": "sk-prev-ds" },
  "temperature": 0.4
}
EOF

cat > "$FH/.config/tau/sessions/work.json" <<'EOF'
{"goal":"migrate the deploy pipeline","turns":7,"history":[{"role":"user","content":"remember this"}]}
EOF

cat > "$FH/.config/tau/snippets/nvim.lua" <<'EOF'
-- tau ACP agent snippets for Neovim — generated by `tau setup --client nvim`.
-- avante.nvim:  providers.tau = { command = "tau", args = { "acp", "serve" } }
EOF

# Zed: a real user settings file — the tau entry lives next to the user's
# own settings and a JSONC comment.
cat > "$FH/.config/zed/settings.json" <<EOF
{
  // user's own settings — must survive tau upgrades untouched
  "theme": "One Dark",
  "agent_servers": {
    "tau": {
      "type": "custom",
      "command": "$PS/bin/tau",
      "args": ["acp", "serve"],
      "env": {}
    }
  }
}
EOF

cat > "$FH/.config/Code/User/settings.json" <<EOF
{
  "editor.fontSize": 13,
  "acp.agents": {
    "tau": {
      "command": "$PS/bin/tau",
      "args": ["acp", "serve"],
      "env": {}
    }
  }
}
EOF

cat > "$FH/.jetbrains/acp.json" <<EOF
{
  "agent_servers": {
    "tau": {
      "command": "$PS/bin/tau",
      "args": ["acp", "serve"],
      "env": {}
    }
  }
}
EOF

STATE_FILES="
$FH/.config/tau/config.json
$FH/.config/tau/sessions/work.json
$FH/.config/tau/snippets/nvim.lua
$FH/.config/zed/settings.json
$FH/.config/Code/User/settings.json
$FH/.jetbrains/acp.json
"

: > "$PS/hashes.before"
for f in $STATE_FILES; do
  [ -f "$f" ] || fail "seeded state file missing: $f"
  hash_file "$f" >> "$PS/hashes.before"
done
echo "e2e-upgrade-keep-state: seeded previous-stable state ($(wc -l < "$PS/hashes.before" | tr -d ' ') files hashed)"

# ── 2. Stage the offline release + run the upgrade ──────────────────────────
mkdir -p "$PS/srv/download/v99.9.9" "$PS/pkg"
cp "$TAU" "$PS/pkg/tau"
chmod +x "$PS/pkg/tau"
tar -czf "$PS/srv/download/v99.9.9/$ASSET" -C "$PS/pkg" tau
(cd "$PS/srv/download/v99.9.9" && { sha256sum "$ASSET" 2>/dev/null || shasum -a 256 "$ASSET"; } > SHA256SUMS.txt)
printf '{"tag_name":"v99.9.9","name":"newer"}' > "$PS/release.json"
cp "$INSTALL_SH" "$PS/install.sh" || fail "install.sh not found at $INSTALL_SH (set TAU_E2E_INSTALL_SH)"

set +e
run_env \
  TAU_UPDATE_URL="file://$PS/release.json" \
  TAU_INSTALL_URL="file://$PS/install.sh" \
  TAU_BASE_URL="file://$PS/srv" \
  TAU_INSTALL_DIR="$PS/bin" \
  "$PS/bin/tau" upgrade --yes < /dev/null > "$PS/upgrade.out" 2> "$PS/upgrade.err"
rc=$?
set -e
[ "$rc" -eq 0 ] || { cat "$PS/upgrade.out" "$PS/upgrade.err" >&2; fail "tau upgrade --yes exited $rc"; }
grep -q '"status":"upgraded"' "$PS/upgrade.out" || { cat "$PS/upgrade.out" >&2; fail "upgrade status not upgraded"; }
[ -x "$PS/bin/tau" ] || fail "upgrade did not leave an executable at $PS/bin/tau"
echo "e2e-upgrade-keep-state: tau upgrade --yes reported status=upgraded"

# ── 3. State must be byte-identical ─────────────────────────────────────────
i=0
for f in $STATE_FILES; do
  i=$((i + 1))
  before="$(sed -n "${i}p" "$PS/hashes.before")"
  after="$(hash_file "$f" 2>/dev/null || echo MISSING)"
  [ "$before" = "$after" ] || fail "state file changed across upgrade: $f"
done
echo "e2e-upgrade-keep-state: config, sessions, snippets, and client wiring are byte-identical"

# ── 4. New binary + old config still work ───────────────────────────────────
run_env "$PS/bin/tau" version > /dev/null || fail "upgraded binary does not run"

got="$(run_env "$PS/bin/tau" config get provider)" \
  || fail "upgraded binary: config get provider failed"
printf '%s' "$got" | grep -q '"value":"xiaomi"' \
  || fail "upgraded binary read wrong provider from old config: $got"

got="$(run_env "$PS/bin/tau" config get keys.deepseek)" \
  || fail "upgraded binary: config get keys.deepseek failed"
printf '%s' "$got" | grep -q '"redacted":true' \
  || fail "upgraded binary did not redact keys.deepseek: $got"
printf '%s' "$got" | grep -q 'sk-prev-ds' \
  && fail "upgraded binary leaked the old keys.deepseek secret: $got"

rep="$(run_env "$PS/bin/tau" config validate)" \
  || fail "upgraded binary: config validate rejected the old-format config: $rep"
printf '%s' "$rep" | grep -q '"ok":true' \
  || fail "upgraded binary: config validate not ok: $rep"

echo "e2e-upgrade-keep-state: upgraded binary reads and validates the previous-stable config"
echo "e2e-upgrade-keep-state: PASS"
