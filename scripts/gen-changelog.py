#!/usr/bin/env python3
"""Regenerate the tagged-release sections of CHANGELOG.md from GitHub release notes.

The release notes published on each GitHub release are the single source of
truth for "what changed" — the same notes `tau upgrade` users audit before
self-updating. This script splices them into CHANGELOG.md between the
`BEGIN/END GENERATED RELEASES` markers so the audited history cannot drift:

    python3 scripts/gen-changelog.py            # rewrite CHANGELOG.md from live release notes
    python3 scripts/gen-changelog.py --check    # exit 1 if CHANGELOG.md is stale
    python3 scripts/gen-changelog.py --from-json tests/fixtures/releases.json --check

Stdlib only. Release notes are fetched from the GitHub API — via `gh api`
when the gh CLI is on PATH, else a plain GET to api.github.com (set
GITHUB_TOKEN/GH_TOKEN to raise the anonymous rate limit). `--from-json`
reads a saved API response (path or `-` for stdin) so tests and offline runs
never touch the network. The repo defaults to javimosch/tau, then
$GITHUB_REPOSITORY (set automatically in Actions), then --repo.

Only the marked region is rewritten — the header, the [Unreleased] section,
and any hand-maintained history below the END marker are preserved, and
`--check` ignores changes outside the markers entirely.
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHANGELOG = ROOT / "CHANGELOG.md"
DEFAULT_REPO = "javimosch/tau"

BEGIN = "<!-- BEGIN GENERATED RELEASES -->"
END = "<!-- END GENERATED RELEASES -->"
NOTE = (
    "<!-- This region is generated by scripts/gen-changelog.py from the "
    "repo's GitHub release notes — edit release notes on GitHub and re-run "
    "the script, do not edit here. -->"
)


def fail(msg):
    print(f"gen-changelog: {msg}", file=sys.stderr)
    sys.exit(2)


def fetch_releases(repo):
    """Return the GitHub API release list for REPO (newest first)."""
    if shutil.which("gh"):
        out = subprocess.run(
            ["gh", "api", f"repos/{repo}/releases", "--paginate"],
            capture_output=True, text=True,
        )
        if out.returncode != 0:
            fail(f"gh api repos/{repo}/releases failed: {out.stderr.strip()}")
        try:
            return json.loads(out.stdout)
        except json.JSONDecodeError as exc:
            fail(f"gh api returned invalid JSON: {exc}")
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    req = urllib.request.Request(
        f"https://api.github.com/repos/{repo}/releases?per_page=100",
        headers={
            "Accept": "application/vnd.github+json",
            "User-Agent": "tau-gen-changelog",
            **({"Authorization": f"Bearer {token}"} if token else {}),
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            return json.loads(resp.read().decode("utf-8"))
    except Exception as exc:
        fail(f"GET api.github.com/repos/{repo}/releases failed: {exc}")


def version_of(tag):
    """Strip a leading v/V prefix from a tag name."""
    return tag[1:] if tag[:1] in ("v", "V") else tag


def normalize_body(body, tag):
    """Adapt a GitHub release body for embedding under a `## [x.y.z]` heading.

    The body's own title line (`## v0.4.0`, `# 0.4.0`, ...) is dropped — the
    generated heading already names the release — and stray `#`/`##`
    headings are demoted to `###` so nothing in the body competes with the
    changelog's section level. Everything else is kept verbatim.
    """
    version = version_of(tag).lower()
    lines = (body or "").split("\n")
    out, title_dropped = [], False
    for line in lines:
        m = re.match(r"^(#{1,6})\s+(.+?)\s*$", line)
        if m and not out and not title_dropped:
            text = m.group(2).strip().lower().lstrip("v")
            if text == version:
                title_dropped = True
                continue
        out.append(line)
    # Drop the blank line(s) left behind by a removed title.
    while out and not out[0].strip():
        out.pop(0)
    while out and not out[-1].strip():
        out.pop()
    return [
        re.sub(r"^#{1,2}(?=\s)", "###", line) if line.startswith("#") else line
        for line in out
    ]


def render(releases, repo):
    """Build the inner generated region (between, excluding, the markers)."""
    published = [
        r for r in releases
        if isinstance(r, dict) and r.get("tag_name") and not r.get("draft")
    ]
    published.sort(key=lambda r: (r.get("published_at") or "", r["tag_name"]),
                   reverse=True)
    blocks = []
    for r in published:
        tag = r["tag_name"]
        date = (r.get("published_at") or "")[:10] or "unreleased"
        head = f"## [{version_of(tag)}] - {date}"
        if r.get("prerelease"):
            head += " _(pre-release)_"
        section = [head, ""] + normalize_body(r.get("body"), tag)
        blocks.append("\n".join(section).rstrip())
    inner = [NOTE, ""]
    if blocks:
        inner.append("\n\n".join(blocks))
        inner += [
            "",
            *(
                f"[{version_of(r['tag_name'])}]: "
                + (r.get("html_url")
                   or f"https://github.com/{repo}/releases/tag/{r['tag_name']}")
                for r in published
            ),
        ]
    else:
        inner.append("_No published releases yet._")
    return "\n".join(inner)


def splice(text, inner):
    """Replace the marked region of TEXT with INNER, preserving the rest."""
    lines = text.split("\n")
    try:
        begin = lines.index(BEGIN)
    except ValueError:
        fail(f"{BEGIN!r} marker not found in changelog — add the marker pair "
             f"around the tagged-release sections")
    try:
        end = lines.index(END, begin + 1)
    except ValueError:
        fail(f"{END!r} marker not found after line {begin + 1} — the "
             f"generated region must be closed")
    return "\n".join(lines[: begin + 1] + inner.split("\n") + lines[end:])


def main():
    ap = argparse.ArgumentParser(
        description="Regenerate CHANGELOG.md's tagged-release sections from "
                    "GitHub release notes.",
    )
    ap.add_argument("--check", action="store_true",
                    help="do not write; exit 1 if the changelog is stale")
    ap.add_argument("--from-json", metavar="PATH",
                    help="read a saved GitHub API releases response "
                         "(''-' for stdin) instead of fetching live notes")
    ap.add_argument("--repo", metavar="OWNER/NAME",
                    help="repository to fetch releases for "
                         "(default: --repo > $GITHUB_REPOSITORY > "
                         + DEFAULT_REPO + ")")
    ap.add_argument("--changelog", metavar="PATH", default=str(CHANGELOG),
                    help="changelog file to rewrite (default: CHANGELOG.md)")
    args = ap.parse_args()

    repo = args.repo or os.environ.get("GITHUB_REPOSITORY") or DEFAULT_REPO
    path = Path(args.changelog)

    if args.from_json:
        raw = sys.stdin.read() if args.from_json == "-" else \
            Path(args.from_json).read_text(encoding="utf-8")
        try:
            releases = json.loads(raw)
        except json.JSONDecodeError as exc:
            fail(f"{args.from_json}: invalid JSON: {exc}")
    else:
        releases = fetch_releases(repo)
    if not isinstance(releases, list):
        fail("releases payload is not a JSON array")

    try:
        current = path.read_text(encoding="utf-8")
    except OSError as exc:
        fail(f"cannot read {path}: {exc}")

    updated = splice(current, render(releases, repo))
    if args.check:
        if updated != current:
            print(f"gen-changelog: {path} is stale — run "
                  f"python3 scripts/gen-changelog.py", file=sys.stderr)
            sys.exit(1)
        return
    if updated != current:
        path.write_text(updated, encoding="utf-8")
        print(f"gen-changelog: updated {path}", file=sys.stderr)


if __name__ == "__main__":
    main()
